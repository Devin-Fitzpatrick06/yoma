// Builds data/synthetic/samples.json: 20 synthetic scored answers per template (10 prompt examples, 10 held-out test).
// Run with `npm run seed`. Deterministic, so re-running gives the same file.
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import fragments from "../data/synthetic/sample-fragments.json";
import localeJson from "../data/synthetic/locales/ng-kano.json";
import rubricsJson from "../data/synthetic/rubrics.json";
import templatesJson from "../data/synthetic/templates.json";
import { Locale, Rubric, Template, type Sample } from "../lib/schema";
import { fillTemplate, slotValues } from "../lib/template";

const SAMPLES_PER_TEMPLATE = 20;
const EXAMPLES_PER_TEMPLATE = 10;
const EDUCATOR_NOISE = 0.15; // chance an educator scores one criterion a level off from the fragment level

function mulberry32(seed: number) {
  return () => {
    seed = (seed + 0x6d2b79f5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const rand = mulberry32(42);
const values = slotValues(Locale.parse(localeJson), 0);
const rubrics = Rubric.array().parse(rubricsJson.items);
const byTemplate = fragments.items as Record<string, Record<string, string[]>>;

const samples: Sample[] = [];
for (const template of Template.array().parse(templatesJson.items)) {
  const criteria = rubrics.find((r) => r.id === template.rubricId)!.criteria;
  for (let k = 0; k < SAMPLES_PER_TEMPLATE; k++) {
    const parts: string[] = [];
    const scores: Record<string, number> = {};
    for (const { id } of criteria) {
      const level = 1 + Math.floor(rand() * 4);
      parts.push(byTemplate[template.id][id][level - 1]);
      const shift = rand() < EDUCATOR_NOISE ? (rand() < 0.5 ? -1 : 1) : 0;
      scores[id] = Math.min(4, Math.max(1, level + shift));
    }
    samples.push({
      id: `${template.id}-${String(k + 1).padStart(2, "0")}`,
      templateId: template.id,
      answer: fillTemplate(parts.filter(Boolean).join(" "), values),
      scores,
      split: k < EXAMPLES_PER_TEMPLATE ? "example" : "test",
    });
  }
}

const out = {
  note: "SYNTHETIC PLACEHOLDER. Generated by scripts/generate-samples.ts; scores imitate an educator. Replace with real educator-scored answers.",
  items: samples,
};
writeFileSync(join(__dirname, "../data/synthetic/samples.json"), JSON.stringify(out, null, 2) + "\n");
console.log(`Wrote ${samples.length} samples`);
